const isPack = process.argv[1]?.endsWith('pack-bin.js') ?? false

const pack: PackUserConfig[] = !isPack
  ? []
  : (
      await Promise.all(
        readdirSync(join(import.meta.dirname, 'packages'))
          .map((dir) => join(import.meta.dirname, 'packages', dir, 'vite.config.ts'))
          .filter((file) => existsSync(file))
          .map(async (file): Promise<PackUserConfig | undefined> => {
            const config = (await import(pathToFileURL(file).href)) as {
              default: { pack?: PackUserConfig }
            }
            return config.default.pack && { cwd: join(file, '..'), ...config.default.pack }
          })
      )
    ).filter((config) => config !== undefined)

